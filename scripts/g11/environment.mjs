import { mkdir, mkdtemp, realpath, writeFile, readFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { chromium } from '@playwright/test';

export const root = fileURLToPath(new URL('../../', import.meta.url));
process.chdir(root);
export const workRoot = path.join(root, '.work');
export const extensionPath = path.join(workRoot, 'g11-measurement-dist');
export const browserPath =
  process.env.G11_BROWSER_PATH || process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || chromium.executablePath();
export const revision = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
export function workPath(value) {
  const absolute = path.resolve(value);
  const relative = path.relative(workRoot, absolute);
  if (!relative || relative.startsWith('..') || path.isAbsolute(relative))
    throw new Error("Measurement output must be inside this checkout's .work directory.");
  return absolute;
}
export async function createProfile() {
  const directory = path.join(workRoot, 'g11-profiles');
  await mkdir(directory, { recursive: true });
  if (process.env.G11_PROFILE) {
    const profile = path.resolve(process.env.G11_PROFILE);
    if (path.dirname(profile) !== directory || !path.basename(profile).startsWith('run-'))
      throw new Error('Only profiles generated by scripts/g11 may be reused.');
    const resolved = await realpath(profile);
    if (path.dirname(resolved) !== (await realpath(directory)))
      throw new Error('A reused profile must remain inside the task profile directory.');
    const marker = JSON.parse(await readFile(path.join(profile, 'g11-owned-profile.json'), 'utf8'));
    if (marker.extensionPath !== extensionPath) throw new Error('Profile belongs to a different measurement build.');
    return profile;
  }
  const profile = await mkdtemp(path.join(directory, 'run-'));
  await writeFile(path.join(profile, 'g11-owned-profile.json'), JSON.stringify({ extensionPath }));
  return profile;
}
